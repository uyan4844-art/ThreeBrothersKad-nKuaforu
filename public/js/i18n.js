class I18nEngine {
  constructor() {
    this.currentLang = this.getInitialLanguage();
    if (typeof document !== 'undefined') {
      this.init();
    }
  }

  getInitialLanguage() {
    if (typeof localStorage === 'undefined') return 'tr';
    const saved = localStorage.getItem('tb_language');
    if (saved && I18N_LANGUAGES[saved]) return saved;

    const browserLang = (typeof navigator !== 'undefined' && (navigator.language || navigator.userLanguage) || 'tr').toLowerCase();
    if (browserLang.startsWith('en')) return 'en';
    if (browserLang.startsWith('de')) return 'de';
    if (browserLang.startsWith('ru')) return 'ru';
    if (browserLang.startsWith('ar')) return 'ar';
    return 'tr';
  }

  setLanguage(lang) {
    if (!I18N_LANGUAGES[lang]) return;
    this.currentLang = lang;
    localStorage.setItem('tb_language', lang);
    this.applyTranslations();
    this.updateDomAttributes();
    this.updateLanguageSwitchers();
  }

  applyTranslations() {
    const translations = I18N_TRANSLATIONS[this.currentLang] || I18N_TRANSLATIONS.tr;
    const elements = document.querySelectorAll('[data-i18n]');

    elements.forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = translations[key];
      if (val !== undefined) {
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          el.placeholder = val;
        } else if (el.tagName === 'TITLE') {
          document.title = val;
        } else {
          el.innerHTML = val;
        }
      }
    });

    const metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc && translations.meta_description) {
      metaDesc.setAttribute('content', translations.meta_description);
    }
  }

  updateDomAttributes() {
    document.documentElement.lang = this.currentLang;
    const dir = I18N_LANGUAGES[this.currentLang].dir || 'ltr';
    document.documentElement.dir = dir;
    if (dir === 'rtl') {
      document.documentElement.classList.add('is-rtl');
    } else {
      document.documentElement.classList.remove('is-rtl');
    }
  }

  updateLanguageSwitchers() {
    const btns = document.querySelectorAll('.lang-btn, [data-lang-select]');
    btns.forEach(btn => {
      const lang = btn.getAttribute('data-lang') || btn.getAttribute('data-lang-select');
      if (lang === this.currentLang) {
        btn.classList.add('active');
      } else {
        btn.classList.remove('active');
      }
    });
  }

  init() {
    if (typeof document === 'undefined' || typeof document.addEventListener !== 'function') return;
    document.addEventListener('DOMContentLoaded', () => {
      this.updateDomAttributes();
      this.applyTranslations();
      this.updateLanguageSwitchers();

      document.querySelectorAll('.lang-btn, [data-lang-select]').forEach(btn => {
        btn.addEventListener('click', (e) => {
          e.preventDefault();
          const lang = btn.getAttribute('data-lang') || btn.getAttribute('data-lang-select');
          if (lang) this.setLanguage(lang);
        });
      });
    });
  }
}

if (typeof window !== 'undefined') {
  window.i18n = new I18nEngine();
  window.I18n = { translations: I18N_TRANSLATIONS, languages: I18N_LANGUAGES };
}

if (typeof module !== 'undefined' && module.exports) {
  module.exports = { I18N_LANGUAGES, I18N_TRANSLATIONS, I18nEngine };
}
